-- H2 schema for the unitemporal pet-store Reladomo model.
-- BUSINESS tables carry FROM_Z / THRU_Z (GenericNonAuditedTemporalDirector).
-- AUDIT tables carry IN_Z / OUT_Z (AuditOnlyTemporalDirector).
-- PLAIN tables have no temporal columns.
-- Physical unique key is logical PK plus the temporal FROM/IN column.

DROP TABLE IF EXISTS FEEDING_SCHEDULE;
DROP TABLE IF EXISTS VETERINARY_VISIT;
DROP TABLE IF EXISTS VACCINATION;
DROP TABLE IF EXISTS GROOMING_APPOINTMENT;
DROP TABLE IF EXISTS SALES_ORDER_LINE;
DROP TABLE IF EXISTS PAYMENT;
DROP TABLE IF EXISTS PURCHASE_ORDER_LINE;
DROP TABLE IF EXISTS SHIPMENT;
DROP TABLE IF EXISTS ADOPTION;
DROP TABLE IF EXISTS SALES_ORDER;
DROP TABLE IF EXISTS PURCHASE_ORDER;
DROP TABLE IF EXISTS STOCK_LEVEL;
DROP TABLE IF EXISTS PET;
DROP TABLE IF EXISTS BREED;
DROP TABLE IF EXISTS KENNEL;
DROP TABLE IF EXISTS EMPLOYEE;
DROP TABLE IF EXISTS PRODUCT;
DROP TABLE IF EXISTS SPECIES;
DROP TABLE IF EXISTS PRODUCT_CATEGORY;
DROP TABLE IF EXISTS PET_OWNER;
DROP TABLE IF EXISTS STORE;
DROP TABLE IF EXISTS SUPPLIER;

CREATE TABLE SPECIES (
    SPECIES_ID BIGINT NOT NULL,
    COMMON_NAME VARCHAR(80) NOT NULL,
    SCIENTIFIC_NAME VARCHAR(120) NOT NULL,
    CARE_LEVEL VARCHAR(32) NOT NULL,
    FROM_Z TIMESTAMP NOT NULL,
    THRU_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX SPECIES_PK ON SPECIES (SPECIES_ID, FROM_Z);

CREATE TABLE BREED (
    BREED_ID BIGINT NOT NULL,
    SPECIES_ID BIGINT NOT NULL,
    NAME VARCHAR(80) NOT NULL,
    SIZE_CATEGORY VARCHAR(32) NOT NULL,
    TYPICAL_LIFESPAN_YEARS INTEGER NOT NULL,
    FROM_Z TIMESTAMP NOT NULL,
    THRU_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX BREED_PK ON BREED (BREED_ID, FROM_Z);

CREATE TABLE STORE (
    STORE_ID BIGINT NOT NULL,
    NAME VARCHAR(80) NOT NULL,
    ADDRESS_LINE1 VARCHAR(120) NOT NULL,
    CITY VARCHAR(64) NOT NULL,
    POSTAL_CODE VARCHAR(16) NOT NULL,
    PHONE VARCHAR(32) NOT NULL,
    OPENED_DATE TIMESTAMP NOT NULL,
    FROM_Z TIMESTAMP NOT NULL,
    THRU_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX STORE_PK ON STORE (STORE_ID, FROM_Z);

CREATE TABLE KENNEL (
    KENNEL_ID BIGINT NOT NULL,
    STORE_ID BIGINT NOT NULL,
    LABEL VARCHAR(64) NOT NULL,
    CAPACITY INTEGER NOT NULL,
    ZONE VARCHAR(32) NOT NULL,
    FROM_Z TIMESTAMP NOT NULL,
    THRU_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX KENNEL_PK ON KENNEL (KENNEL_ID, FROM_Z);

CREATE TABLE PRODUCT_CATEGORY (
    CATEGORY_ID BIGINT NOT NULL,
    NAME VARCHAR(80) NOT NULL,
    PARENT_CATEGORY_ID BIGINT
);
CREATE UNIQUE INDEX PRODUCT_CATEGORY_PK ON PRODUCT_CATEGORY (CATEGORY_ID);

CREATE TABLE PRODUCT (
    PRODUCT_ID BIGINT NOT NULL,
    SKU VARCHAR(32) NOT NULL,
    NAME VARCHAR(120) NOT NULL,
    CATEGORY_ID BIGINT NOT NULL,
    UNIT_PRICE DECIMAL(18, 2) NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL,
    FROM_Z TIMESTAMP NOT NULL,
    THRU_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX PRODUCT_PK ON PRODUCT (PRODUCT_ID, FROM_Z);

CREATE TABLE PET (
    PET_ID BIGINT NOT NULL,
    NAME VARCHAR(80) NOT NULL,
    SPECIES_ID BIGINT NOT NULL,
    BREED_ID BIGINT,
    DATE_OF_BIRTH TIMESTAMP NOT NULL,
    SEX VARCHAR(16) NOT NULL,
    COLOR_CODE VARCHAR(32) NOT NULL,
    MICROCHIP_ID VARCHAR(64),
    STATUS VARCHAR(32) NOT NULL,
    KENNEL_ID BIGINT,
    LIST_PRICE DECIMAL(18, 2) NOT NULL,
    FROM_Z TIMESTAMP NOT NULL,
    THRU_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX PET_PK ON PET (PET_ID, FROM_Z);

CREATE TABLE FEEDING_SCHEDULE (
    SCHEDULE_ID BIGINT NOT NULL,
    PET_ID BIGINT NOT NULL,
    FEED_TIME_OF_DAY VARCHAR(16) NOT NULL,
    PRODUCT_ID BIGINT NOT NULL,
    QUANTITY_GRAMS INTEGER NOT NULL,
    FROM_Z TIMESTAMP NOT NULL,
    THRU_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX FEEDING_SCHEDULE_PK ON FEEDING_SCHEDULE (SCHEDULE_ID, FROM_Z);

CREATE TABLE VETERINARY_VISIT (
    VISIT_ID BIGINT NOT NULL,
    PET_ID BIGINT NOT NULL,
