    FOLLOW_UP_DATE TIMESTAMP,
    IN_Z TIMESTAMP NOT NULL,
    OUT_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX VETERINARY_VISIT_PK ON VETERINARY_VISIT (VISIT_ID, IN_Z);

CREATE TABLE VACCINATION (
