    OUT_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX VACCINATION_PK ON VACCINATION (VACCINATION_ID, IN_Z);

CREATE TABLE GROOMING_APPOINTMENT (
    APPOINTMENT_ID BIGINT NOT NULL,
    PET_ID BIGINT NOT NULL,
    GROOMER_ID BIGINT NOT NULL,
    SCHEDULED_TIME TIMESTAMP NOT NULL,
    SERVICE_CODE VARCHAR(32) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    IN_Z TIMESTAMP NOT NULL,
    OUT_Z TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX GROOMING_APPOINTMENT_PK ON GROOMING_APPOINTMENT (APPOINTMENT_ID, IN_Z);

CREATE TABLE STOCK_LEVEL (
    STOCK_ID BIGINT NOT NULL,
